using System;
using Unity.Netcode;
using UnityEngine;

/// <summary>
/// Action bits carried by the fixed-tick input stream.  Combat remains
/// authoritative in CombatSystem; these bits make the movement stream
/// replayable and observable without trusting the client for damage.
/// </summary>
public static class HybridInputAction
{
    // Keep action flags byte-sized so command packets stay compact.
    public const byte None = 0;
    public const byte Attack = 1 << 0;
    public const byte KnownMask = Attack;
}

/// <summary>
/// One client input sample.  PredictedPosition is a report used for server
/// validation only; it never becomes authoritative server state.
/// </summary>
[Serializable]
public struct HybridInputCommand : INetworkSerializable, IEquatable<HybridInputCommand>
{
    public uint Tick;
    public Vector3 MoveDirection;
    public bool Jump;
    public byte ActionFlags;
    public bool MovementLocked;
    public Vector3 RootMotionDelta;
    public float RootMotionYaw;
    /// <summary>
    /// A bounded, deterministic displacement generated by an authoritative
    /// gameplay motion profile (for example an attack lunge).  It is recorded
    /// in the prediction history so reconciliation can replay the exact
    /// profile slice that was rendered locally.  The server never trusts this
    /// value from the wire; it substitutes its own profile output.
    /// </summary>
    public Vector3 ScriptedMotionDelta;
    public Vector3 PredictedPosition;
    public float PredictedYaw;

    public void NetworkSerialize<T>(BufferSerializer<T> serializer) where T : IReaderWriter
    {
        serializer.SerializeValue(ref Tick);
        serializer.SerializeValue(ref MoveDirection);
        serializer.SerializeValue(ref Jump);
        serializer.SerializeValue(ref ActionFlags);
        serializer.SerializeValue(ref MovementLocked);
        serializer.SerializeValue(ref RootMotionDelta);
        serializer.SerializeValue(ref RootMotionYaw);
        serializer.SerializeValue(ref ScriptedMotionDelta);
        serializer.SerializeValue(ref PredictedPosition);
        serializer.SerializeValue(ref PredictedYaw);
    }

    public bool Equals(HybridInputCommand other)
    {
        return Tick == other.Tick
            && MoveDirection == other.MoveDirection
            && Jump == other.Jump
            && ActionFlags == other.ActionFlags
            && MovementLocked == other.MovementLocked
            && RootMotionDelta == other.RootMotionDelta
            && Mathf.Approximately(RootMotionYaw, other.RootMotionYaw)
            && ScriptedMotionDelta == other.ScriptedMotionDelta
            && PredictedPosition == other.PredictedPosition
            && Mathf.Approximately(PredictedYaw, other.PredictedYaw);
    }

    public override bool Equals(object obj)
    {
        return obj is HybridInputCommand other && Equals(other);
    }

    public override int GetHashCode()
    {
        unchecked
        {
            int hash = (int)Tick;
            hash = hash * 31 + MoveDirection.GetHashCode();
            hash = hash * 31 + Jump.GetHashCode();
            hash = hash * 31 + ActionFlags.GetHashCode();
            hash = hash * 31 + MovementLocked.GetHashCode();
            hash = hash * 31 + RootMotionDelta.GetHashCode();
            hash = hash * 31 + RootMotionYaw.GetHashCode();
            hash = hash * 31 + ScriptedMotionDelta.GetHashCode();
            hash = hash * 31 + PredictedPosition.GetHashCode();
            hash = hash * 31 + PredictedYaw.GetHashCode();
            return hash;
        }
    }
}

/// <summary>
/// Authoritative logical state replicated by the server.  InputTick is the
/// last client command represented by this state; SimulationTick also moves
/// while the server is applying a held input during packet loss.
/// </summary>
[Serializable]
public struct HybridMotionState : INetworkSerializable, IEquatable<HybridMotionState>
{
    public uint SimulationTick;
    public uint InputTick;
    public Vector3 Position;
    public Vector3 Velocity;
    public float Yaw;
    public bool Grounded;
    public byte ActionFlags;

    public Quaternion Rotation => Quaternion.Euler(0f, Yaw, 0f);

    public void NetworkSerialize<T>(BufferSerializer<T> serializer) where T : IReaderWriter
    {
        serializer.SerializeValue(ref SimulationTick);
        serializer.SerializeValue(ref InputTick);
        serializer.SerializeValue(ref Position);
        serializer.SerializeValue(ref Velocity);
        serializer.SerializeValue(ref Yaw);
        serializer.SerializeValue(ref Grounded);
        serializer.SerializeValue(ref ActionFlags);
    }

    public bool Equals(HybridMotionState other)
    {
        return SimulationTick == other.SimulationTick
            && InputTick == other.InputTick
            && Position == other.Position
            && Velocity == other.Velocity
            && Mathf.Approximately(Yaw, other.Yaw)
            && Grounded == other.Grounded
            && ActionFlags == other.ActionFlags;
    }

    public override bool Equals(object obj)
    {
        return obj is HybridMotionState other && Equals(other);
    }

    public override int GetHashCode()
    {
        unchecked
        {
            int hash = (int)SimulationTick;
            hash = hash * 31 + (int)InputTick;
            hash = hash * 31 + Position.GetHashCode();
            hash = hash * 31 + Velocity.GetHashCode();
            hash = hash * 31 + Yaw.GetHashCode();
            hash = hash * 31 + Grounded.GetHashCode();
            hash = hash * 31 + ActionFlags.GetHashCode();
            return hash;
        }
    }
}

public struct HybridMotionStep
{
    public Vector3 Motion;
    public Vector3 Velocity;
    public float Yaw;
    public bool Grounded;
    public float HorizontalSpeed;
}

/// <summary>
/// Shared deterministic part of movement.  CharacterController collision is
/// deliberately kept outside this class so the same intent can run on the
/// owner and on the server while each side resolves its own capsule contacts.
/// </summary>
public static class HybridMotionSimulator
{
    public static HybridMotionStep Evaluate(
        Vector3 moveDirection,
        bool jump,
        bool movementLocked,
        Vector3 rootMotionDelta,
        float rootMotionYaw,
        float currentYaw,
        Vector3 currentVelocity,
        bool grounded,
        float moveSpeed,
        float gravity,
        float groundedGravity,
        float jumpHeight,
        float turnSpeed,
        float rootMotionWeight,
        float rootMotionMaxMultiplier,
        bool allowRootMotion,
        Vector3 scriptedMotionDelta,
        float deltaTime)
    {
        deltaTime = Mathf.Max(0.0001f, deltaTime);
        moveSpeed = Mathf.Max(0f, moveSpeed);
        gravity = Mathf.Min(-0.01f, gravity);
        groundedGravity = Mathf.Min(-0.01f, groundedGravity);
        jumpHeight = Mathf.Max(0f, jumpHeight);
        turnSpeed = Mathf.Max(0f, turnSpeed);

        moveDirection = SanitizeMoveDirection(moveDirection);
        if (movementLocked)
            moveDirection = Vector3.zero;

        float verticalVelocity = IsFinite(currentVelocity.y) ? currentVelocity.y : 0f;
        if (grounded && verticalVelocity < 0f)
            verticalVelocity = groundedGravity;
        else
            verticalVelocity += gravity * deltaTime;

        if (jump && grounded && !movementLocked)
        {
            verticalVelocity = Mathf.Sqrt(jumpHeight * -2f * gravity);
            grounded = false;
        }

        Vector3 inputDisplacement = moveDirection * (moveSpeed * deltaTime);
        Vector3 horizontalDisplacement = inputDisplacement;

        if (allowRootMotion && !movementLocked)
        {
            Vector3 safeRootMotion = SanitizeRootMotion(
                rootMotionDelta,
                moveDirection,
                moveSpeed,
                deltaTime,
                rootMotionMaxMultiplier);

            if (safeRootMotion.sqrMagnitude > 0.000001f)
            {
                float weight = Mathf.Clamp01(rootMotionWeight);
                horizontalDisplacement = Vector3.Lerp(inputDisplacement, safeRootMotion, weight);
            }
        }

        // Scripted gameplay motion (attack lunge, dodge, knockback, etc.) is
        // deliberately applied after the input/root-motion blend.  It must
        // remain active while normal movement is locked by an attack.
        if (IsFinite(scriptedMotionDelta))
        {
            scriptedMotionDelta.y = 0f;
            horizontalDisplacement += scriptedMotionDelta;
        }

        Vector3 horizontal = horizontalDisplacement / deltaTime;
        Vector3 velocity = new Vector3(horizontal.x, verticalVelocity, horizontal.z);

        float targetYaw = currentYaw;
        Vector3 facingDirection = moveDirection.sqrMagnitude > 0.0001f
            ? moveDirection
            : new Vector3(horizontalDisplacement.x, 0f, horizontalDisplacement.z);
        if (facingDirection.sqrMagnitude > 0.0001f)
            targetYaw = Mathf.Atan2(facingDirection.x, facingDirection.z) * Mathf.Rad2Deg;

        if (allowRootMotion && IsFinite(rootMotionYaw) && Mathf.Abs(rootMotionYaw) > 0.001f)
        {
            float boundedRootYaw = Mathf.Clamp(rootMotionYaw, -90f, 90f);
            float rootTargetYaw = currentYaw + boundedRootYaw;
            targetYaw = Mathf.LerpAngle(targetYaw, rootTargetYaw, Mathf.Clamp01(rootMotionWeight));
        }

        float yaw = Mathf.MoveTowardsAngle(
            IsFinite(currentYaw) ? currentYaw : 0f,
            targetYaw,
            turnSpeed * deltaTime);

        Vector3 motion = horizontalDisplacement;
        motion.y = verticalVelocity * deltaTime;

        return new HybridMotionStep
        {
            Motion = motion,
            Velocity = velocity,
            Yaw = yaw,
            Grounded = grounded,
            HorizontalSpeed = new Vector3(horizontal.x, 0f, horizontal.z).magnitude,
        };
    }

    public static Vector3 SanitizeMoveDirection(Vector3 value)
    {
        if (!IsFinite(value))
            return Vector3.zero;

        value.y = 0f;
        return Vector3.ClampMagnitude(value, 1f);
    }

    public static Vector3 SanitizeRootMotion(
        Vector3 value,
        Vector3 moveDirection,
        float moveSpeed,
        float deltaTime,
        float maxMultiplier)
    {
        if (!IsFinite(value))
            return Vector3.zero;

        value.y = 0f;
        float maxDistance = Mathf.Max(0.05f, moveSpeed * deltaTime * Mathf.Max(1f, maxMultiplier));
        if (value.magnitude > maxDistance)
            value = value.normalized * maxDistance;

        Vector3 input = SanitizeMoveDirection(moveDirection);
        if (value.sqrMagnitude > 0.000001f && input.sqrMagnitude > 0.0001f)
        {
            float directionDot = Vector3.Dot(value.normalized, input.normalized);
            if (directionDot < -0.25f)
                return Vector3.zero;
        }

        return value;
    }

    /// <summary>
    /// Bounds an externally generated motion slice before it reaches the
    /// CharacterController.  Attack profiles are normally much smaller than
    /// this limit; the guard also keeps malformed network data harmless.
    /// </summary>
    public static Vector3 SanitizeScriptedMotion(Vector3 value, float maxDistance = 2f)
    {
        if (!IsFinite(value))
            return Vector3.zero;

        value.y = 0f;
        maxDistance = Mathf.Max(0.05f, maxDistance);
        if (value.magnitude > maxDistance)
            value = value.normalized * maxDistance;
        return value;
    }

    public static bool IsFinite(Vector3 value)
    {
        return IsFinite(value.x) && IsFinite(value.y) && IsFinite(value.z);
    }

    public static bool IsFinite(float value)
    {
        return !float.IsNaN(value) && !float.IsInfinity(value);
    }
}
